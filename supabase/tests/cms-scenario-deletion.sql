 INSERT INTO public.choices(choice_id,scenario_id,version_id,next_scenario_id) VALUES(gen_random_uuid(),other,v,sid);
 BEGIN PERFORM public.cms_delete_scenario(v,1,req,sid); RAISE EXCEPTION 'Incoming destination accepted'; EXCEPTION WHEN raise_exception THEN ASSERT SQLERRM='Scenario has external dependencies; nothing was deleted'; END;
 DELETE FROM public.choices WHERE scenario_id=other AND next_scenario_id=sid;
 BEGIN PERFORM public.cms_delete_scenario(v,0,req,sid); RAISE EXCEPTION 'Stale accepted'; EXCEPTION WHEN serialization_failure THEN NULL; END;
 result:=public.cms_delete_scenario(v,1,req,sid);
